DIST = Path(os.environ.get("DIST", HERE.parent / "dist")).resolve()
PROJECT = Path(os.environ.get("PROJECT", HERE.parent / "project")).resolve()
PORT = int(os.environ.get("PORT", "7777"))
TOKEN = os.environ.get("TOKEN", os.urandom(8).hex())
